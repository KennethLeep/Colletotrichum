export ASSEMBLY="$PROJECT_DIR/Assembly"
export ANNOTATION="$PROJECT_DIR/Annotation"
export PAN="$PROJECT_DIR/Pangenome"

###########################
# ASSEMBLY SUBDIRECTORIES #
###########################

export TRIMS="$ASSEMBLY/ExportedTrims"
